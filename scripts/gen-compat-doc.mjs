#!/usr/bin/env node
// Writes docs/postman-compatibility.md from the compatibility matrix
// (packages/core/test/pm-compat/cases.ts), whose every row is a test (P3.11,
// risk R10). With --check it writes nothing and exits 1 if the file is out
// of date.
//
// Usage: node scripts/gen-compat-doc.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
// Node runs the TypeScript file as it is: it holds no syntax that needs a compiler.
import { CASES } from "../packages/core/test/pm-compat/cases.ts";

const TARGET = "docs/postman-compatibility.md";
const LEGACY = /^(postman\.|tests\[|response|request \(|environment \(|globals \(|iteration$|legacy )/;

/**
 * The section a row belongs to: its heading, and the anchor the app's error
 * messages link to (`… is not supported — see docs/postman-compatibility.md#pm-cookies`).
 */
export function sectionOf(api) {
  const pm = /^pm\.([A-Za-z]+)/.exec(api);
  if (pm) return { anchor: `pm-${pm[1].toLowerCase()}`, title: `\`pm.${pm[1]}\`` };
  if (api.startsWith("require")) return { anchor: "require", title: "`require`" };
  if (LEGACY.test(api)) return { anchor: "legacy", title: "Postman's older sandbox" };
  return { anchor: "globals", title: "`console`, timers and encoding" };
}

const STATUS = { supported: "Supported", partial: "Partial", unsupported: "Not supported" };
const cell = (text) => text.replaceAll("|", "\\|");

/** What the document says of a row beside its status. */
function noteOf(row) {
  if (row.note) return row.note;
  return row.status === "unsupported" ? "Throws `WayfarerUnsupportedError`, which names what was called." : "";
}

export function render(cases) {
  const count = (status) => cases.filter((row) => row.status === status).length;
  const sections = new Map();
  for (const row of cases) {
    const { anchor, title } = sectionOf(row.api);
    if (!sections.has(anchor)) sections.set(anchor, { title, rows: [] });
    sections.get(anchor).rows.push(row);
  }
  const lines = [
    "# Postman compatibility",
    "",
    "<!-- Generated by scripts/gen-compat-doc.mjs from packages/core/test/pm-compat/cases.ts. Do not edit: change the rows and run `npm run gen:compat`. -->",
    "",
    "What a pre-request or a post-response script can use of Postman's script",
    "API in Wayfarer. Every row below is a test: its script runs in Node and in",
    "the app's own worker in a browser, on every commit, and must show what the",
    "row says. This file is written from those rows, and CI fails when it and",
    "they differ. <!-- claim:C-040 -->",
    "",
    `${cases.length} rows: ${count("supported")} supported, ${count("partial")} partial, ${count("unsupported")} not supported.`,
    "",
    "- **Supported:** as in Postman.",
    "- **Partial:** it is there, and the note says what differs.",
    "- **Not supported:** calling it throws `WayfarerUnsupportedError` with the",
    "  name of what was called and a link to its section here, unless the note",
    "  says the name does not exist at all.",
    "",
    "How scripts run, what they can reach and which may run is in",
    "[`scripts.md`](scripts.md).",
    "",
  ];
  for (const [anchor, { title, rows }] of sections) {
    lines.push(`<a id="${anchor}"></a>`, "", `## ${title}`, "", "| API | Status | Note |", "|---|---|---|");
    for (const row of rows) lines.push(`| \`${cell(row.api)}\` | ${STATUS[row.status]} | ${cell(noteOf(row))} |`);
    lines.push("");
  }
  return lines.join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const check = process.argv.includes("--check");
  const next = render(CASES);
  let current = "";
  try {
    current = readFileSync(TARGET, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (next === current) {
    console.log(`${TARGET} is up to date.`);
  } else if (check) {
    console.error(`${TARGET} is out of date with packages/core/test/pm-compat/cases.ts. Run npm run gen:compat.`);
    process.exit(1);
  } else {
    writeFileSync(TARGET, next);
    console.log(`Wrote ${TARGET}.`);
  }
}
